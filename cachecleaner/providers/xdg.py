"""XDG / desktop-environment cache providers.

All of these are classic, regenerable caches living under ``$XDG_CACHE_HOME``.
Trash is deliberately NOT handled here: it can contain user files, so it is
out of scope for a *cache* cleaner (documented design decision, rule 5.2).
"""

from __future__ import annotations

import os

from ..core.provider import CachePath, CacheProvider, Category
from ..core.safety import SafetyLevel

__all__ = [
    "ThumbnailsProvider", "FontconfigProvider", "MesaShaderCacheProvider",
    "KdeSycocaProvider",
]


class ThumbnailsProvider(CacheProvider):
    id = "xdg.thumbnails"
    name = "Thumbnails"
    category = Category.DESKTOP
    safety = SafetyLevel.SAFE_CACHE

    def detect(self) -> bool:
        return os.path.isdir(os.path.join(self.ctx.xdg_cache, "thumbnails"))

    def cache_paths(self) -> list[CachePath]:
        return [CachePath(
            os.path.join(self.ctx.xdg_cache, "thumbnails"),
            "Image/video thumbnail previews (file managers rebuild them on demand)",
            SafetyLevel.SAFE_CACHE,
        )]

    def explain(self) -> str:
        return ("Deletes cached image and video previews generated by file managers "
                "and galleries. They are recreated automatically; the only cost is a "
                "brief delay the next time a folder with media is opened.")


